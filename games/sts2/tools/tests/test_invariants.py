"""The one-home contract for cross-stage hardening rules.

M8.0 change 5 consolidates the rules that fire at every stage into
`modmaker/invariants.md`, because they were restated per stage with wording that
did not match. "Never misreport a Tier" was written three ways in `SKILL.md`,
`verify.md`, and `repair.md`.

Consolidation alone would make things *worse* under the pack's lazy-loading
architecture: a stage page that only points at a rule it used to state has zero
copies of it whenever `invariants.md` was not read. Drifting wording still states
a rule three times; a dangling pointer states it none. So the contract these
tests hold is two-sided:

1. `invariants.md` is registered as eagerly loaded, so a pointer always resolves
   into something actually in context;
2. every `INV-n` reference names a rule that exists, every rule is referenced by
   at least one stage, and the canonical general phrasings appear in exactly one
   file — the removed restatements cannot creep back.

Case 2's last clause is the one that fails if someone "helpfully" re-adds a
summary of INV-1 to `verify.md`. That is how the three copies arose.
"""
from __future__ import annotations

import re
import unittest
from pathlib import Path

import skill_prose


INVARIANTS_PAGE = "invariants.md"
EXPECTED_IDS = tuple(f"INV-{n}" for n in range(1, 11))

# Canonical wording that must live in exactly one file. Each phrase is the
# general statement of a rule that used to be restated per stage; a stage page
# may name the rule and add stage-specific detail, but not re-derive it.
SINGLE_DEFINITION_PHRASES = (
    "A green build is not a load",
    "exit code or from memory of what was written",
    "Every generated symbol comes from this pack",
    "do not make a value balanced, fun",
    "Half-doing the request and reporting it as done",
    "Re-asking a settled question is not a safe default",
    "never emit prompt-derived Harmony",
    "An in-place edit makes the next run unreproducible",
    # INV-9, added by M8.2. The canonical statement of why a local reimplementation of a
    # broken shared route is not a repair; `repair.md` names the rule and adds only its own
    # stage detail.
    "An approximation inside the consumer project is not a repair",
    "Every player-facing localization table ships in English and Simplified Chinese",
)

# Exact restatements removed by change 5, keyed by the file that held them.
# Their return is the drift this Package closed.
REMOVED_RESTATEMENTS: dict[str, tuple[str, ...]] = {
    "verify.md": (
        "never claim the effect is verified when only load was",
        "Be honest about the tier.",
    ),
    "repair.md": (
        "Never fake success.",
        "Don't invent an API.",
        "do not edit it at runtime",
    ),
    "SKILL.md": (
        "Never claim the effect is verified when",
        "A green build is not success.",
    ),
    "quirks.md": ("Do not edit this file from inside a generated mod project.",),
}


class InvariantsPageTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        modmaker = skill_prose.MODMAKER_DIR
        cls.page = (modmaker / INVARIANTS_PAGE).read_text(encoding="utf-8")
        cls.pages = {
            path.relative_to(modmaker).as_posix(): path.read_text(encoding="utf-8")
            for path in sorted(modmaker.rglob("*.md"))
        }

    def test_every_expected_invariant_is_defined_exactly_once(self) -> None:
        headings = re.findall(r"^##\s+(INV-\d+)\b", self.page, re.MULTILINE)
        self.assertEqual(list(EXPECTED_IDS), headings)

    def test_each_invariant_states_where_it_fires(self) -> None:
        bodies = re.split(r"^##\s+INV-\d+.*$", self.page, flags=re.MULTILINE)[1:]
        self.assertEqual(len(EXPECTED_IDS), len(bodies))
        for inv_id, body in zip(EXPECTED_IDS, bodies):
            with self.subTest(invariant=inv_id):
                self.assertIn(
                    "Fires at:",
                    body,
                    f"{inv_id} does not say which stages it constrains",
                )

    def test_the_page_declares_itself_eagerly_loaded(self) -> None:
        """A pointer is only an improvement while the target is in context."""
        self.assertIn("lazily loaded", self.page)
        skill = self.pages["SKILL.md"]
        self.assertIn("`invariants.md` is", skill)
        self.assertIn("Pipeline start; stays in context", skill)
        self.assertIn("read invariants.md", skill)


class InvariantReferenceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        modmaker = skill_prose.MODMAKER_DIR
        cls.pages = {
            path.relative_to(modmaker).as_posix(): path.read_text(encoding="utf-8")
            for path in sorted(modmaker.rglob("*.md"))
        }

    def references(self) -> dict[str, set[str]]:
        found: dict[str, set[str]] = {}
        for name, text in self.pages.items():
            if name == INVARIANTS_PAGE:
                continue
            ids = set(re.findall(r"\bINV-\d+\b", text))
            if ids:
                found[name] = ids
        return found

    def test_every_reference_names_a_defined_invariant(self) -> None:
        for name, ids in self.references().items():
            for inv_id in sorted(ids):
                with self.subTest(page=name, invariant=inv_id):
                    self.assertIn(
                        inv_id,
                        EXPECTED_IDS,
                        f"{name} points at {inv_id}, which invariants.md does not define",
                    )

    def test_every_invariant_is_referenced_by_a_stage(self) -> None:
        """An invariant nobody points at is a rule the pipeline never reaches."""
        referenced = set().union(*self.references().values())
        for inv_id in EXPECTED_IDS:
            with self.subTest(invariant=inv_id):
                self.assertIn(
                    inv_id,
                    referenced,
                    f"{inv_id} is defined but no stage page names it",
                )

    def test_canonical_wording_lives_in_exactly_one_file(self) -> None:
        for phrase in SINGLE_DEFINITION_PHRASES:
            holders = sorted(n for n, t in self.pages.items() if phrase in t)
            with self.subTest(phrase=phrase):
                self.assertEqual(
                    [INVARIANTS_PAGE],
                    holders,
                    f"{phrase!r} is canonical wording; found in {holders}",
                )

    def test_the_removed_restatements_stay_removed(self) -> None:
        for name, phrases in REMOVED_RESTATEMENTS.items():
            page = self.pages[name]
            for phrase in phrases:
                with self.subTest(page=name, phrase=phrase):
                    self.assertNotIn(
                        phrase,
                        page,
                        f"{name} restates an invariant instead of naming it: {phrase!r}",
                    )


if __name__ == "__main__":
    unittest.main()
